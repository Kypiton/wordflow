import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { test } from 'node:test';
import { createDatabaseClient } from '../.next/database-tools/src/lib/db/prisma.js';
import { PrismaQuizRepository } from '../.next/database-tools/src/lib/db/quiz-repository.js';
import { VocabularyRepository } from '../.next/database-tools/src/lib/db/vocabulary-repository.js';
import { seedInitialWord } from '../.next/database-tools/prisma/seed.js';
const url = process.env.TEST_DATABASE_URL;
let allowed = false;
try { const host = new URL(url).hostname; allowed = host.startsWith('ep-nameless-hall') && host.endsWith('.neon.tech'); } catch {}
test('Personal vocabulary: ownership, immutable history and self-review', { skip: !(allowed && process.env.WORDFLOW_DB_TESTS === '1') }, async t => {
  const db = createDatabaseClient(url), peer = createDatabaseClient(url);
  const vocab = new VocabularyRepository(() => db), otherVocab = new VocabularyRepository(() => peer);
  const quiz = new PrismaQuizRepository(() => db), otherQuiz = new PrismaQuizRepository(() => peer);
  const users = []; let messageId = 20000;
  const user = () => { const id = Number.parseInt(randomBytes(6).toString('hex'), 16); users.push(BigInt(id)); return id; };
  const cmd = (id, text, reply) => vocab.process(id, ++messageId, text, reply);
  const add = async (id, term, translation = 'перевод') => {
    const draft = await cmd(id, `/add ${term} — ${translation}`); assert.ok(draft.promptToken, draft.text);
    const done = await cmd(id, `/confirm ${draft.promptToken}`); assert.match(done.text, /Сохранено/);
    return db.personalWord.findUniqueOrThrow({ where: { ownerId_termKey: { ownerId: BigInt(id), termKey: term.toLowerCase() } }, include: { versions: true } });
  };
  const confirm = async (id, text) => { const response = await cmd(id, text); assert.ok(response.promptToken, response.text); return cmd(id, `/confirm ${response.promptToken}`); };
  const create = async (id, mode = 'LEARN') => { const result = await quiz.create(id, id, mode); assert.equal(result.kind, 'widget', result.message); const m = ++messageId; await quiz.bind(result.id, m, result.sendToken); return { ...result, userId: id, messageId: m }; };
  const query = (session, action, changes = {}) => ({ id: randomBytes(12).toString('hex'), from: { id: session.userId, is_bot: false }, chat: { id: session.userId, type: 'private' }, message_id: session.messageId, chat_instance: `personal-${session.userId}`, type: { type: 'data' }, data: `q:${session.id}:${action}`, ...changes });
  const rows = session => db.sessionItem.findMany({ where: { sessionId: session.id }, orderBy: { position: 'asc' }, include: { word: true } });
  try {
    await seedInitialWord(db);
    await t.test('two-step replies, cancellation, expiry, duplicates and two independent owners', async () => {
      const id = user(), another = user();
      assert.equal(await cmd(id, 'несolicited'), null);
      const draft = await cmd(id, '/add   Overwhelmed');
      assert.ok(draft.promptToken);
      await vocab.bindPrompt(id, draft.promptToken, 900);
      assert.equal(await cmd(id, 'подавленный', 899), null);
      const preview = await cmd(id, '  подавленный  ', 900);
      assert.match(preview.text, /Overwhelmed — подавленный/);
      const request = ++messageId;
      const results = await Promise.all([vocab.process(id, request, `/confirm ${preview.promptToken}`), otherVocab.process(id, request, `/confirm ${preview.promptToken}`)]);
      assert.deepEqual(results[0], results[1]);
      assert.equal(await db.personalWord.count({ where: { ownerId: BigInt(id) } }), 1);
      assert.match((await cmd(id, '/add overwhelmed — другой')).text, /уже есть/);
      const foreign = await add(another, 'overwhelmed', 'перегруженный');
      assert.match((await cmd(another, `/confirm ${preview.promptToken}`)).text, /истекло|отсутствует/);
      assert.match((await cmd(id, '/mywords')).text, /подавленный/);
      assert.doesNotMatch((await cmd(id, '/mywords')).text, /перегруженный/);
      assert.equal(foreign.ownerId, BigInt(another));
      const cancelled = await cmd(id, '/add second — второй');
      await cmd(id, `/cancel ${cancelled.promptToken}`);
      assert.match((await cmd(id, `/confirm ${cancelled.promptToken}`)).text, /истекло|отсутствует/);
      await cmd(id, '/add expired');
      await db.vocabularyDraft.update({ where: { userId: BigInt(id) }, data: { expiresAt: new Date(0) } });
      assert.match((await cmd(id, '/translation истёкший')).text, /истекло/);
      assert.equal(await db.personalWord.count({ where: { ownerId: BigInt(id) } }), 1);
    });
    await t.test('paginated private lists, optional edits and archive/restore', async () => {
      const id = user(), another = user();
      for (const term of ['one', 'two', 'three', 'four', 'five', 'six']) await add(id, term);
      const first = await cmd(id, '/mywords'); const second = await cmd(id, '/mywords 2');
      assert.match(first.text, /6 всего/); assert.match(first.text, /Страница 1\/2/); assert.match(second.text, /Страница 2\/2/);
      assert.equal((first.text.match(/ — перевод/g) ?? []).length, 5);
      assert.equal((second.text.match(/ — перевод/g) ?? []).length, 1);
      assert.match((await cmd(id, '/mywords 3')).text, /нет/);
      assert.match((await cmd(another, '/edit one')).text, /не найдено/);
      await confirm(id, '/pos one — noun');
      // Reset only this synthetic user's rate window for the remaining test commands.
      await db.telegramUser.update({ where: { id: BigInt(id) }, data: { vocabularyWindowAt: new Date(0) } });
      await confirm(id, '/example one — One example.');
      await confirm(id, '/example one — -');
      const word = await db.word.findFirstOrThrow({ where: { personalWord: { ownerId: BigInt(id), termKey: 'one' }, isCurrent: true } });
      assert.equal(word.partOfSpeech, 'noun'); assert.equal(word.example, null);
      await confirm(id, '/delete one');
      assert.doesNotMatch((await cmd(id, '/mywords')).text, /one —/);
      assert.match((await cmd(id, '/mywords archived')).text, /one —/);
      await confirm(id, '/restore one');
      assert.equal((await db.personalWord.findUniqueOrThrow({ where: { ownerId_termKey: { ownerId: BigInt(id), termKey: 'one' } } })).archivedAt, null);
    });
    await t.test('GENERAL/PERSONAL/MIXED selection, active session snapshot and foreign isolation', async () => {
      const id = user(), other = user(); await add(id, 'personal phrase'); await add(id, 'Reluctant'); await add(other, 'secret phrase');
      const general = await create(id); assert.equal(general.total, 10);
      assert.ok((await rows(general)).every(i => i.word.personalWordId === null));
      await cmd(id, '/mode PERSONAL');
      assert.equal((await quiz.create(id, id)).kind, 'message');
      assert.equal((await db.studySession.findUnique({ where: { id: general.id } })).vocabularyMode, 'GENERAL');
      await quiz.revoke(general.id);
      const personal = await create(id); assert.equal(personal.total, 2); assert.equal(personal.content.kind, 'self');
      assert.ok((await rows(personal)).every(i => i.word.personalWordId));
      await quiz.revoke(personal.id); await cmd(id, '/mode MIXED');
      const mixed = await create(id); const mixedRows = await rows(mixed);
      assert.equal(mixed.total, 10); assert.equal(new Set(mixedRows.map(i => i.word.term.toLowerCase())).size, 10);
      assert.ok(mixedRows.every(i => i.word.term !== 'secret phrase'));
      assert.ok(mixedRows.some(i => i.word.personalWordId));
      await quiz.revoke(mixed.id);
      await confirm(id, '/delete personal phrase'); await confirm(id, '/delete Reluctant'); await cmd(id, '/mode PERSONAL');
      assert.equal((await quiz.create(id, id)).kind, 'message');
    });
    await t.test('self-review requires reveal, commits once, persists SRS, reviews due only and preserves edited history', async () => {
      const id = user(), outsider = user(); const entry = await add(id, 'overwhelmed', 'подавленный'); await cmd(id, '/mode PERSONAL');
      const session = await create(id), [item] = await rows(session);
      assert.equal((await quiz.process(query(session, '0:k'))).feedback.status, 'error');
      assert.equal((await quiz.process(query(session, '0:a0'))).feedback.status, 'error');
      assert.equal((await quiz.process(query(session, '0:r', { from: { id: outsider, is_bot: false }, chat: { id: outsider, type: 'private' } }))).feedback.status, 'error');
      const reveal = await quiz.process(query(session, '0:r'));
      assert.equal(reveal.feedback.status, 'recall'); assert.equal(reveal.feedback.answer, 'подавленный');
      assert.ok(Buffer.byteLength(JSON.stringify(reveal.feedback)) <= 1024);
      assert.equal(await db.reviewAttempt.count({ where: { sessionItemId: item.id } }), 0);
      assert.equal(await db.userWordProgress.count({ where: { userId: BigInt(id) } }), 0);
      const retry = query(session, '0:k');
      await Promise.all([quiz.process(retry), otherQuiz.process(retry)]);
      await otherQuiz.process(query(session, '0:f'));
      const old = await db.reviewAttempt.findUniqueOrThrow({ where: { sessionItemId: item.id } });
      assert.equal(old.correct, true); assert.equal(old.selfRating, true); assert.equal(old.selectedPosition, null);
      const saved = await peer.userWordProgress.findUniqueOrThrow({ where: { userId_wordId: { userId: BigInt(id), wordId: item.wordId } } });
      assert.equal(saved.repetitions, 1); assert.equal(saved.intervalMinutes, 1440);
      assert.equal((await quiz.process(query(session, '0:n'))).feedback.accuracy, 100);
      assert.equal((await quiz.create(id, id, 'REVIEW')).kind, 'message');
      await db.userWordProgress.update({ where: { userId_wordId: { userId: BigInt(id), wordId: item.wordId } }, data: { dueAt: new Date(0), lastReviewedAt: new Date(0) } });
      const review = await create(id, 'REVIEW'); await quiz.process(query(review, '0:r')); await quiz.process(query(review, '0:f'));
      const lapsed = await db.userWordProgress.findUniqueOrThrow({ where: { userId_wordId: { userId: BigInt(id), wordId: item.wordId } } });
      assert.equal(lapsed.intervalMinutes, 10); assert.equal(lapsed.repetitions, 0); assert.equal(lapsed.lapses, 1);
      await confirm(id, '/edit overwhelmed — перегруженный');
      assert.deepEqual(await db.reviewAttempt.findUnique({ where: { id: old.id } }), old);
      const versions = await db.word.findMany({ where: { personalWordId: entry.id }, orderBy: { version: 'asc' } });
      assert.equal(versions.length, 2); assert.equal(versions[0].translation, 'подавленный'); assert.equal(versions[0].isCurrent, false);
      assert.equal(versions[1].translation, 'перегруженный');
      assert.equal(await db.userWordProgress.count({ where: { wordId: versions[0].id, userId: BigInt(id) } }), 1);
      const newSession = await create(id); assert.equal((await rows(newSession))[0].wordId, versions[1].id);
      await db.studySession.update({ where: { id: newSession.id }, data: { expiresAt: new Date(0) } });
      assert.equal((await quiz.process(query(newSession, '0:r'))).feedback.status, 'expired');
    });
    await t.test('active snapshots survive edits/archive; conflicting ratings and failed writes preserve one outcome', async () => {
      const id = user(); const entry = await add(id, 'snapshot', 'снимок'); await cmd(id, '/mode PERSONAL');
      const session = await create(id), [item] = await rows(session);
      await confirm(id, '/edit snapshot — состояние');
      await confirm(id, '/delete snapshot');
      const revealed = await quiz.process(query(session, '0:r'));
      assert.equal(revealed.feedback.answer, 'снимок');
      assert.equal((await otherQuiz.process(query(session, 's'))).feedback.status, 'recall');
      const rejecting = db.$extends({ query: { widgetQueryReceipt: { async create() { throw new Error('injected failure'); } } } });
      await assert.rejects(new PrismaQuizRepository(() => rejecting).process(query(session, '0:k')));
      assert.equal(await db.reviewAttempt.count({ where: { sessionItemId: item.id } }), 0);
      assert.equal(await db.userWordProgress.count({ where: { userId: BigInt(id) } }), 0);
      const results = await Promise.all([quiz.process(query(session, '0:k')), otherQuiz.process(query(session, '0:f'))]);
      assert.equal(results.filter(r => r.feedback.status === 'answered').length, 1);
      assert.equal(await db.reviewAttempt.count({ where: { sessionItemId: item.id } }), 1);
      const attempt = await db.reviewAttempt.findUniqueOrThrow({ where: { sessionItemId: item.id } });
      const progress = await db.userWordProgress.findUniqueOrThrow({ where: { userId_wordId: { userId: BigInt(id), wordId: item.wordId } } });
      assert.equal(progress.intervalMinutes, attempt.correct ? 1440 : 10);
      assert.equal(progress.lastAttemptId, attempt.id);
      assert.equal((await quiz.create(id, id)).kind, 'message');
      await confirm(id, '/restore snapshot');
      const restored = await create(id);
      assert.notEqual((await rows(restored))[0].wordId, item.wordId);
      assert.equal(await db.word.count({ where: { personalWordId: entry.id } }), 2);
      assert.deepEqual(await db.reviewAttempt.findUnique({ where: { id: attempt.id } }), attempt);
    });
    await t.test('receipts reject altered/stale messages and failed confirmations roll back creation', async () => {
      const id = user(), another = user();
      const draft = await cmd(id, '/add rollback — откат');
      await cmd(another, '/add foreign — чужой');
      assert.match((await cmd(another, `/confirm ${draft.promptToken}`)).text, /Неверный код/);
      const request = ++messageId;
      const rejecting = db.$extends({ query: { vocabularyReceipt: { async create() { throw new Error('injected failure'); } } } });
      await assert.rejects(new VocabularyRepository(() => rejecting).process(id, request, `/confirm ${draft.promptToken}`));
      assert.equal(await db.personalWord.count({ where: { ownerId: BigInt(id) } }), 0);
      assert.ok(await db.vocabularyDraft.findUnique({ where: { userId: BigInt(id) } }));
      assert.match((await vocab.process(id, request, `/confirm ${draft.promptToken}`)).text, /Сохранено/);
      assert.match((await vocab.process(id, request, '/delete rollback')).text, /Неверный повтор/);
      assert.match((await vocab.process(id, request - 1, '/delete rollback')).text, /устарело/);
      assert.equal(await db.personalWord.count({ where: { ownerId: BigInt(id), archivedAt: null } }), 1);
    });
    await t.test('rate limit and invalid input leave vocabulary unchanged', async () => {
      const id = user();
      assert.match((await cmd(id, '/add слово — перевод')).text, /английское/);
      assert.match((await cmd(id, '/add word — ')).text, /Введите/);
      await db.telegramUser.update({ where: { id: BigInt(id) }, data: { vocabularyWindowAt: new Date(), vocabularyRequestCount: 20 } });
      assert.match((await cmd(id, '/add blocked — заблокирован')).text, /Слишком много/);
      assert.equal(await db.personalWord.count({ where: { ownerId: BigInt(id) } }), 0);
    });
  } finally {
    try { for (const userId of users) await db.$transaction(async tx => {
      await tx.vocabularyDraft.deleteMany({ where: { userId } }); await tx.vocabularyReceipt.deleteMany({ where: { userId } });
      await tx.userWordProgress.deleteMany({ where: { userId } }); await tx.widgetQueryReceipt.deleteMany({ where: { session: { userId } } });
      await tx.reviewAttempt.deleteMany({ where: { item: { session: { userId } } } }); await tx.sessionItem.deleteMany({ where: { session: { userId } } });
      await tx.learnRequest.deleteMany({ where: { userId } }); await tx.studySession.deleteMany({ where: { userId } });
      await tx.word.deleteMany({ where: { personalWord: { ownerId: userId } } }); await tx.personalWord.deleteMany({ where: { ownerId: userId } });
      await tx.telegramUser.deleteMany({ where: { id: userId } });
    }); } finally { await Promise.all([db.$disconnect(), peer.$disconnect()]); }
  }
});
