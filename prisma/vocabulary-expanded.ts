export type CefrLevel = keyof typeof supplementalVocabulary;
export type CatalogRow = {
  slug: string; term: string; partOfSpeech: string; translation: string; example: string; level: CefrLevel;
};

export function parseCatalog(): CatalogRow[] {
  return (Object.entries(supplementalVocabulary) as [CefrLevel, string][]).flatMap(([level, data]) =>
    data.trim().split("\n").map((line, index) => {
      const fields = line.split("|");
      if (fields.length !== 4 || fields.some(field => !field.trim())) throw new Error(`Invalid ${level} vocabulary row ${index + 1}`);
      const [term, partOfSpeech, translation, example] = fields;
      return { slug: term.toLowerCase(), term, partOfSpeech, translation, example, level };
    })
  );
}
